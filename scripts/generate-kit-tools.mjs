import { build } from 'esbuild';
import { builtinModules } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const output = join(root, 'kit/ohmatekit/tools');
const result = await build({
  absWorkingDir: root, entryPoints: ['packages/cli/src/integrate/kit-tools.ts'],
  outfile: join(output, 'runtime.mjs'), bundle: true, minify: true, write: false,
  platform: 'node', target: 'node22', format: 'esm', metafile: true,
  banner: { js: "// Generated by scripts/generate-kit-tools.mjs. Do not edit.\n" +
    "import { createRequire } from 'node:module'; const require = createRequire(import.meta.url);" },
});
const builtins = new Set([...builtinModules, ...builtinModules.map(name => 'node:' + name)]);
for (const item of Object.values(result.metafile.outputs)) {
  for (const dependency of item.imports) {
    if (dependency.external && !builtins.has(dependency.path)) { throw new Error('NON_STANDALONE_KIT_TOOL: ' + dependency.path); }
  }
}
const files = new Map([['runtime.mjs', result.outputFiles[0].text]]);
for (const tool of ['doctor', 'generate-integration', 'verify-release']) {
  files.set(tool + '.mjs', "// Generated by scripts/generate-kit-tools.mjs. Do not edit.\n" +
    "import { kitToolMain } from './runtime.mjs';\nawait kitToolMain('" + tool + "', process.argv.slice(2));\n");
}
const sources = [];
for (const file of Object.keys(result.metafile.inputs).filter(file => !file.includes('node_modules/')).sort()) {
  const bytes = await readFile(join(root, file));
  sources.push({ path: file, sha256: createHash('sha256').update(bytes).digest('hex') });
}
files.set('build-manifest.json', JSON.stringify({ schemaVersion: '1.0', generator: 'scripts/generate-kit-tools.mjs',
  sources, artifacts: [...files].map(([path, text]) => ({ path, bytes: Buffer.byteLength(text),
    sha256: createHash('sha256').update(text).digest('hex') })), standalone: true,
  compilerBinding: 'unverified', releasePurity: 'unverified' }, null, 2) + '\n');
if (!process.argv.includes('--check')) { await mkdir(output, { recursive: true }); }
for (const [file, text] of files) {
  if (process.argv.includes('--check')) {
    if (await readFile(join(output, file), 'utf8') !== text) { throw new Error('KIT_TOOL_DRIFT: ' + file); }
  } else { await writeFile(join(output, file), text); }
}
console.log(JSON.stringify({ generated: [...files.keys()], sourceInputs: sources.length,
  runtimeBytes: Buffer.byteLength(files.get('runtime.mjs')), check: process.argv.includes('--check') }));
