import { readFile, writeFile } from 'node:fs/promises';
import { coreProblemSchemas } from '../packages/cli/src/problem-package/core-profile.ts';
const target = new URL('../kit/ohmatekit/src/main/ets/core/GeneratedCoreContract.ets', import.meta.url);
const text = '// Generated by scripts/generate-core-contract.mjs. Do not edit.\n' +
  `export const CORE_PROBLEM_SCHEMAS: string = ${JSON.stringify(JSON.stringify(Object.fromEntries(coreProblemSchemas())))};\n`;
if (process.argv.includes('--check')) {
  if (await readFile(target,'utf8') !== text) { throw new Error('CORE_CONTRACT_DRIFT'); }
} else {
  await writeFile(target,text);
}
console.log(process.argv.includes('--check') ? 'Core contract matches canonical schemas' : 'Core contract generated');
