import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createHandshake } from '../packages/cli/src/debug-protocol/handshake.ts';
import { describeReadonlyProtocol } from '../packages/cli/src/debug-protocol/contract.ts';
import { COOKIE_METADATA_SUMMARY } from '../packages/cli/src/debug-protocol/domain-schemas.ts';
import { problemSchemas } from '../packages/cli/src/problem-package/schemas.ts';
import { KIT_DOMAINS } from '../packages/cli/src/problem-package/kit-profile.ts';

const root = new URL('../examples/OHMateKitProducer/', import.meta.url);
const identity = {
  project: 'contract', buildId: 'unverified', device: 'contract',
  process: 'contract', sessionId: 'contract', fingerprint: '0'.repeat(64),
};
const offers = createHandshake(identity).channels;
const schemas = Object.fromEntries(problemSchemas(true, true, true, true));
const exportSchemas = Object.fromEntries(problemSchemas(false, false, false, true, true));
const readonlyExportSchemas = Object.fromEntries(problemSchemas(false, false, false, true, 'app-readonly-summary'));
const memory = KIT_DOMAINS.find((domain) => domain.domain === 'memory');
const ui = KIT_DOMAINS.find((domain) => domain.domain === 'ui');
const network = KIT_DOMAINS.find((domain) => domain.domain === 'network-summary');
const webDom = KIT_DOMAINS.find((domain) => domain.domain === 'web-dom');
const webConsole = KIT_DOMAINS.find((domain) => domain.domain === 'web-console');
const storage = KIT_DOMAINS.find((domain) => domain.domain === 'arkweb');
const dfx = KIT_DOMAINS.find((domain) => domain.domain === 'dfx');
const outputs = new Map([
  ['entry/src/main/ets/bridge/GeneratedContract.ets',
    '// Generated by scripts/generate-kit-contract.mjs. Do not edit.\n' +
    `export const CHANNEL_CONTRACTS: string = ${JSON.stringify(JSON.stringify(offers))};\n` +
    `export const PROBLEM_SCHEMAS: string = ${JSON.stringify(JSON.stringify(schemas))};\n` +
    `export const KIT_EXPORT_SCHEMAS: string = ${JSON.stringify(JSON.stringify(exportSchemas))};\n` +
    `export const KIT_READONLY_EXPORT_SCHEMAS: string = ${JSON.stringify(JSON.stringify(readonlyExportSchemas))};\n` +
    `export const KIT_DOMAIN_NAMES: string = ${JSON.stringify(JSON.stringify(KIT_DOMAINS.map((item) => item.domain)))};\n` +
    `export const KIT_MEMORY_PATH: string = ${JSON.stringify(memory.path)};\n` +
    `export const KIT_DFX_PATH: string = ${JSON.stringify(dfx.path)};\n` +
    `export const KIT_UI_PATH: string = ${JSON.stringify(ui.path)};\n` +
    `export const KIT_NETWORK_PATH: string = ${JSON.stringify(network.path)};\n` +
    `export const KIT_WEB_DOM_DIRECTORY: string = ${JSON.stringify(webDom.directory)};\n` +
    `export const KIT_WEB_CONSOLE_PATH: string = ${JSON.stringify(webConsole.path)};\n` +
    `export const KIT_WEB_STORAGE_PATH: string = ${JSON.stringify(storage.path)};\n` +
    `export const KIT_STORAGE_SUMMARY: string = ${JSON.stringify(COOKIE_METADATA_SUMMARY)};\n`],
  ['entry/src/main/resources/rawfile/ohmate-protocol.json', `${JSON.stringify(describeReadonlyProtocol(), null, 2)}\n`],
  ['entry/src/main/resources/rawfile/ohmate-problem-schemas.json', `${JSON.stringify(schemas, null, 2)}\n`],
]);
for (const [name, content] of outputs) {
  const target = new URL(name, root);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== content) { throw new Error(`KIT_CONTRACT_DRIFT: ${name}`); }
  } else {
    await mkdir(fileURLToPath(new URL('.', target)), { recursive: true });
    await writeFile(target, content);
  }
}
console.log(process.argv.includes('--check') ? 'Kit contract matches protocol sources' : 'Kit contract generated');
