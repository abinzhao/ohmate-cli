interface Source { line: number; offset: number; bytes: number; sha256: string }
interface Report {
  analyzer: string; completeness: string; input: { sha256: string; bytes: number; format: string };
  signal: { name: string; code: string; address: string | null; sender: { pid: number; uid: number } | null; hintSha256: string | null };
  thread: { tid: number; nameSha256: string; source: Source };
  fields: Record<string, { sha256: string; bytes: number }>; fieldSources: Record<string, Source>;
  frames: { ordinal: number; declaredIndex: number; pc: string; locationSha256: string;
    functionSha256: string | null; functionOffset: string | null; buildId: string | null; source: Source }[];
  summary: { frameCount: number; declaredFunctionCount: number; declaredBuildIdCount: number; unknownLocationCount: number };
  checks: { captureIdentity: string; buildIdentity: string; rootCause: string; symbols: string;
    applicationOwnership: string; registerAnalysis: string; buildIdAssociation: string };
  coverage: { missingFields: string[]; sections: { name: string; source: Source }[]; fingerprintMeaning: string;
    rawText: string; supplementaryAnalysis: string; pcMeaning: string };
  candidates: { code: string; evidenceLevel: string; alternatives: string[] }[];
}
async function setup(value: string | Buffer = log) {
  const root = await mkdtemp(join(tmpdir(), 'ohmate-cppcrash-test-')); roots.push(root);
  const file = join(root, 'capture.log'); await writeFile(file, value);
  const context = await createExecutionContext({ cwd: root, dataDir: join(root, 'data') }), runtime = await createRuntime();
  return { root, file, context, runtime, execute: (input: unknown = { log: file }) => runtime.execute('analyze.cppcrash', input, context) };
}
it('registers a read-only bounded Native faultlog subset', async () => {
  const { runtime } = await setup();
  expect(runtime.registry.get('analyze.cppcrash')).toMatchObject({ command: ['analyze', 'cppcrash'], risk: 'R0',
    requirements: [], idempotency: 'read', recovery: 'verify-and-retry' });
  expect(runtime.registry.get('analyze.cppcrash')!.description).toContain('subset');
});
it('binds raw signal and frame declarations without certifying symbols, device or build', async () => {
  const { file, execute } = await setup(), receipt = await execute(), data = receipt.data as Report;
  expect(receipt.exitCode).toBe(3);
  expect(data).toMatchObject({ analyzer: 'cppcrash', completeness: 'incomplete',
    input: { sha256: hash(await readFile(file)), bytes: Buffer.byteLength(log), format: 'oh-cppcrash-native-stack-subset' },
    signal: { name: 'SIGSEGV', code: 'SI_USER', address: '0x00001e99', sender: { pid: 7833, uid: 0 }, hintSha256: null },
    thread: { tid: 6946, nameSha256: hash('e.myapplication') },
    summary: { frameCount: 1, declaredFunctionCount: 0, declaredBuildIdCount: 1, unknownLocationCount: 0 },
    checks: { captureIdentity: 'unverified', buildIdentity: 'unverified', rootCause: 'not-established', symbols: 'not-resolved',
      applicationOwnership: 'not-established', registerAnalysis: 'not-performed', buildIdAssociation: 'not-performed' },
    coverage: { fingerprintMeaning: 'fault-clustering-hash-not-build-id', rawText: 'not-persisted',
      pcMeaning: 'relative-or-absolute-unverified' } });
  expect(data.frames[0]).toMatchObject({ ordinal: 0, declaredIndex: 0, pc: '000a8a94',
    locationSha256: hash('/system/lib/ld-musl-arm.so.1'), functionSha256: null, functionOffset: null,
    buildId: '3753ef9108517347d1a03e903b3a5dbf' });
  expect(receipt.artifacts).toHaveLength(1);
  expect(JSON.parse(await readFile(receipt.artifacts[0].path, 'utf8'))).toEqual(data);
  expect(hash(await readFile(receipt.artifacts[0].path))).toBe(receipt.artifacts[0].sha256);
  expect(data.candidates[0]).toMatchObject({ code: 'native-signal-declared', evidenceLevel: 'single-feature' });
  expect(data.candidates[0].alternatives.length).toBeGreaterThan(1);
});
it('preserves full 64-bit hex and signed function offsets rather than converting through Number', async () => {
  const text = log.replace('0x00001e99', '0xffffffffffffffff').replace(frame,
    '#00 pc ffffffffffffffff /data/storage/el1/bundle/libs/arm64/libentry.so(Foo::operator()()+-9223372036854775808)(abcdef12)\n' +
    '#01 pc ffffffffffffffff /data/storage/el1/bundle/libs/arm64/libentry.so(Foo::operator()()+9223372036854775807)\n' +
    '#02 pc 0000000000000000 [Unknown]\n');
  const receipt = await (await setup(text)).execute(), data = receipt.data as Report;
  expect(receipt.exitCode).toBe(3); expect(data.signal.address).toBe('0xffffffffffffffff');
  expect(data.frames.map(row => row.pc)).toEqual(['ffffffffffffffff', 'ffffffffffffffff', '0000000000000000']);
  expect(data.frames.map(row => row.functionOffset)).toEqual(['-9223372036854775808', '9223372036854775807', null]);
  expect(data.frames[0].functionSha256).toBe(hash('Foo::operator()()'));
  expect(data.summary).toMatchObject({ declaredFunctionCount: 2, declaredBuildIdCount: 1, unknownLocationCount: 1 });
  expect(data.checks.applicationOwnership).toBe('not-established');
});
