  const { file, execute } = await setup(), receipt = await execute(), data = receipt.data as Report;
  expect(receipt.exitCode).toBe(3);
  expect(data).toMatchObject({ analyzer: 'freeze', completeness: 'incomplete', reason: 'THREAD_BLOCK_6S',
    input: { sha256: hash(await readFile(file)), bytes: Buffer.byteLength(log), format: 'oh-appfreeze-event-stack-subset' },
    summary: { phaseCount: 1, threadCount: 1, frameCount: 2, targetStackCount: 1, sameTargetTid: null },
    checks: { systemFactors: 'not-evaluated', threadState: 'undetermined', rootCause: 'not-established',
      responsibility: 'undetermined', sampleAssociation: 'not-performed', symbols: 'not-resolved',
      captureIdentity: 'unverified', buildIdentity: 'unverified' } });
  expect(data.phases[0]).toMatchObject({ event: 'THREAD_BLOCK_3S', pid: 13680, uid: 20020177,
    targetTid: 13680, targetBasis: 'main-pid-declared', targetThreadOrdinal: 0 });
  expect(data.phases[0].threads[0].frames).toMatchObject([
    { kind: 'native', pc: '000000000000186c', locationSha256: hash('[shmm]'), functionOffset: '72' },
    { kind: 'js', pc: null, functionSha256: hash('wait15s'), locationSha256: hash('entry/src/main/ets/pages/Index.ets'), line: 16, column: 10 } ]);
  expect(data.candidates[0]).toMatchObject({ code: 'freeze-event-declared', evidenceLevel: 'single-feature' });
  expect(data.candidates[0].alternatives.length).toBeGreaterThan(1);
  expect(JSON.parse(await readFile(receipt.artifacts[0].path, 'utf8'))).toEqual(data);
  expect(hash(await readFile(receipt.artifacts[0].path))).toBe(receipt.artifacts[0].sha256);
