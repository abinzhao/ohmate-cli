it('preserves raw CRLF byte ranges for every field, phase, thread and frame', async () => {
  const text = log.replaceAll('\n', '\r\n').trimEnd(), receipt = await (await setup(text)).execute(), data = receipt.data as Report;
  expect(receipt.exitCode).toBe(3); const bytes = Buffer.from(text);
  const sources = [...Object.values(data.fields).map(row => row.source),
    ...data.phases.flatMap(row => [row.source, ...Object.values(row.fields).map(field => field.source),
      ...row.sections.map(section => section.source), ...row.threads.flatMap(thread => [thread.source, ...thread.frames.map(frame => frame.source)])])];
  for (const source of sources) {
    expect(hash(bytes.subarray(source.offset, source.offset + source.bytes))).toBe(source.sha256);
    expect(source.line).toBe(bytes.subarray(0, source.offset).toString().split('\n').length);
  }
});
