interface Source { line: number; offset: number; bytes: number; sha256: string }
interface Field { sha256: string; bytes: number; source: Source }
interface Frame { ordinal: number; kind: string; pc: string | null; buildId: string | null;
  functionSha256: string | null; locationSha256: string; functionOffset: string | null;
  line: number | null; column: number | null; source: Source }
interface Phase {
  event: string; pid: number; uid: number; targetTid: number | null; targetBasis: string;
  targetThreadOrdinal: number | null; fields: Record<string, Field>;
  threads: { tid: number; nameSha256: string; source: Source; frames: Frame[]; state: Field | null }[];
  sections: { name: string; source: Source }[]; source: Source;
}
interface Report {
  analyzer: string; completeness: string; input: { sha256: string; bytes: number; format: string };
  reason: string; fields: Record<string, Field>; phases: Phase[];
  summary: { phaseCount: number; threadCount: number; frameCount: number; targetStackCount: number; sameTargetTid: boolean | null };
  checks: { systemFactors: string; threadState: string; rootCause: string; responsibility: string;
    sampleAssociation: string; symbols: string; captureIdentity: string; buildIdentity: string };
  coverage: { rawText: string; supplementaryAnalysis: string; fingerprintMeaning: string; sampleStacks: string; limits: Record<string, number> };
  candidates: { code: string; evidenceLevel: string; alternatives: string[] }[];
}
async function setup(value: string | Buffer = log) {
  const root = await mkdtemp(join(tmpdir(), 'ohmate-freeze-test-')); roots.push(root);
  const file = join(root, 'capture.log'); await writeFile(file, value);
  const context = await createExecutionContext({ cwd: root, dataDir: join(root, 'data') }), runtime = await createRuntime();
  return { root, file, context, runtime, execute: (input: unknown = { log: file }) => runtime.execute('analyze.freeze', input, context) };
}
it('registers an offline read-only Freeze subset', async () => {
  const { runtime } = await setup();
  expect(runtime.registry.get('analyze.freeze')).toMatchObject({ command: ['analyze', 'freeze'], risk: 'R0',
    requirements: [], idempotency: 'read', recovery: 'verify-and-retry' });
  expect(runtime.registry.get('analyze.freeze')!.description).toContain('subset');
});
