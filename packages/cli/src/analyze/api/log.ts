import { setImmediate } from 'node:timers/promises';
import { digest } from '../../quality/evidence.js';
import { API_LIMITS, type APIEvent, type APIParsed, type APISource } from './types.js';

const envelope = /^(\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3})[ \t]+(\d+)[ \t]+(\d+)[ \t]+([DIWEF])[ \t]+C([0-9a-fA-F]{5})\/([^:\r\n]+):[ \t]*(.*)$/;
const marker = /(?:^|[\s,;])(?:error[ \t]+)?code[ \t]*[:=][ \t]*/gi;
export function decodeAPIText(bytes: Buffer, budget: number): string {
  const text = bytes.toString('utf8');
  if (!bytes.length || bytes.length > budget || !Buffer.from(text).equals(bytes) || text.includes('\0') ||
    bytes.subarray(0, 3).equals(Buffer.from([0xef, 0xbb, 0xbf]))) { throw new Error('API_TEXT_UNSUPPORTED'); }
  return text;
}
export function positiveAPIInteger(value: string): number {
  const number = Number(value);
  if (!/^[1-9][0-9]*$/.test(value) || !Number.isSafeInteger(number)) { throw new Error('API_NUMBER_UNSUPPORTED'); }
  return number;
}
function validateTime(value: string) {
  const [month, day, hour, minute, second] = value.match(/\d+/g)!.map(Number);
  if (month < 1 || month > 12 || day < 1 || day > [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31][month - 1] ||
    hour > 23 || minute > 59 || second > 59) { throw new Error('API_TIME_UNSUPPORTED'); }
}
function explicitCode(message: string): number | null {
  const markers = [...message.matchAll(marker)];
  if (!markers.length) { return null; }
  if (markers.length !== 1) { throw new Error('API_CODE_AMBIGUOUS'); }
  const remaining = message.slice(markers[0].index! + markers[0][0].length);
  const value = /^([^,;\s]*)/.exec(remaining)![1];
  return positiveAPIInteger(value);
}
function event(text: string, source: APISource): APIEvent | null {
  if (!text.trim()) { return null; }
  if (/^\s*(?:Generated by HiviewDFX|Reason:|\.{3}|\[truncated\])/i.test(text)) { throw new Error('API_INPUT_TYPE_UNSUPPORTED'); }
  const match = envelope.exec(text);
  if (!match) {
    if ([...text.matchAll(marker)].length) { throw new Error('API_ENVELOPE_UNSUPPORTED'); }
    return null;
  }
  validateTime(match[1]);
  const pid = positiveAPIInteger(match[2]), tid = positiveAPIInteger(match[3]);
  if (Buffer.byteLength(match[6]) > API_LIMITS.nameBytes) { throw new Error('API_NAME_LIMIT'); }
  if (match[4] !== 'E' && match[4] !== 'F') { return null; }
  const code = explicitCode(match[7]);
  return code === null ? null : { code, pid, tid, level: match[4], domain: match[5],
    tagSha256: digest(match[6]), timeSha256: digest(match[1]), messageSha256: digest(match[7]), source };
}
export async function parseAPILog(bytes: Buffer, signal: AbortSignal): Promise<APIParsed> {
  signal.throwIfAborted(); decodeAPIText(bytes, API_LIMITS.fileBytes);
  const events: APIEvent[] = [];
  let offset = 0, lines = 0, contextLineCount = 0;
  while (offset < bytes.length) {
    signal.throwIfAborted();
    const newline = bytes.indexOf(10, offset), end = newline < 0 ? bytes.length : newline + 1, raw = bytes.subarray(offset, end);
    if (++lines > API_LIMITS.lines || raw.length > API_LIMITS.lineBytes) { throw new Error('API_LINE_LIMIT'); }
    const parsed = event(raw.toString('utf8').replace(/\r?\n$/, ''), { line: lines, offset, bytes: raw.length, sha256: digest(raw) });
    if (parsed) {
      if (events.length === API_LIMITS.events) { throw new Error('API_EVENT_LIMIT'); }
      events.push(parsed);
    } else { contextLineCount++; }
    offset = end;
    if (lines % 512 === 0) { await setImmediate(); }
  }
  signal.throwIfAborted();
  if (!events.length) { throw new Error('API_INPUT_TYPE_UNSUPPORTED'); }
  return { events, contextLineCount };
}
