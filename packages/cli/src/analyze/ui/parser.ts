import { setImmediate } from 'node:timers/promises';
import { digest } from '../../quality/evidence.js';
import { UI_ANALYSIS_LIMITS, type ContextReason, type UIEvent, type UIParsed, type WindowNotice } from './types.js';

const envelope = /^(\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3})[ \t]+(\d+)[ \t]+(\d+)[ \t]+I[ \t]+C03900\/Ace:[ \t]*(.*)$/;
const message = /^\[(?:ui_content_impl\.cpp\(([0-9]+)\)-)?\((-?[0-9]+):(-?[0-9]+):([a-z]+)\)\][ \t]+\[([^\]\r\n]+)\]\[([^\]\r\n]+)\]\[([0-9]+)\]: window ([a-z]+)$/;
const reasons = new Set(['scope', 'active', 'default', 'singleton', 'foreground', 'undefined']);
const statuses = new Set(['focus', 'unfocus', 'foreground', 'background', 'destroy']);
function decode(bytes: Buffer) {
  const text = bytes.toString('utf8');
  if (!bytes.length || bytes.length > UI_ANALYSIS_LIMITS.fileBytes || !Buffer.from(text).equals(bytes) ||
    text.includes('\0') || bytes.subarray(0, 3).equals(Buffer.from([0xef, 0xbb, 0xbf]))) { throw new Error('UI_ANALYSIS_TEXT_UNSUPPORTED'); }
}
function integer(value: string, context = false, zero = false): number {
  const number = Number(value);
  if (!/^(?:0|[1-9][0-9]*|-[1-9][0-9]*)$/.test(value) || !Number.isSafeInteger(number) ||
    (context ? number < -2147483648 || number > 2147483647 : number < (zero ? 0 : 1))) {
    throw new Error('UI_ANALYSIS_NUMBER_UNSUPPORTED');
  }
  return number;
}
function validateTime(value: string) {
  const [month, day, hour, minute, second] = value.match(/\d+/g)!.map(Number);
  if (month < 1 || month > 12 || day < 1 || day > [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31][month - 1] ||
    hour > 23 || minute > 59 || second > 59) { throw new Error('UI_ANALYSIS_TIME_UNSUPPORTED'); }
}
function parseEvent(text: string, source: UIEvent['source']): UIEvent | null {
  if (/^\s*(?:Generated by HiviewDFX|Reason:|\.{3}|\[truncated\])/i.test(text)) { throw new Error('UI_ANALYSIS_INPUT_TYPE_UNSUPPORTED'); }
  if (!/\bwindow\b/.test(text) && !/C03900\/Ace:.*\][ \t]+\[[^\]]+\]\[[^\]]+\]\[[0-9]+\]:/.test(text)) { return null; }
  const outer = envelope.exec(text), fields = outer && message.exec(outer[4]);
  if (!outer || !fields) { throw new Error('UI_ANALYSIS_EVENT_UNSUPPORTED'); }
  validateTime(outer[1]);
  if (!reasons.has(fields[4]) || !statuses.has(fields[8])) { throw new Error('UI_ANALYSIS_ENUM_UNSUPPORTED'); }
  if (Buffer.byteLength(fields[5]) > UI_ANALYSIS_LIMITS.nameBytes || Buffer.byteLength(fields[6]) > UI_ANALYSIS_LIMITS.nameBytes) {
    throw new Error('UI_ANALYSIS_NAME_LIMIT');
  }
  const instanceId = integer(fields[7], true, true);
  if (instanceId < 0) { throw new Error('UI_ANALYSIS_NUMBER_UNSUPPORTED'); }
  return { status: fields[8] as WindowNotice, currentId: integer(fields[2], true), trackedId: integer(fields[3], true),
    reason: fields[4] as ContextReason, instanceId, pid: integer(outer[2]), tid: integer(outer[3]),
    bundleSha256: digest(fields[5]), moduleSha256: digest(fields[6]), timeSha256: digest(outer[1]),
    prefix: { kind: fields[1] === undefined ? 'release' : 'debug', sourceLine: fields[1] === undefined ? null : integer(fields[1]) },
    source };
}
export async function parseUIEvents(bytes: Buffer, signal: AbortSignal): Promise<UIParsed> {
  signal.throwIfAborted(); decode(bytes);
  const events: UIEvent[] = [];
  let offset = 0, lines = 0, contextLineCount = 0;
  while (offset < bytes.length) {
    signal.throwIfAborted();
    const newline = bytes.indexOf(10, offset), end = newline < 0 ? bytes.length : newline + 1, raw = bytes.subarray(offset, end);
    if (++lines > UI_ANALYSIS_LIMITS.lines || raw.length > UI_ANALYSIS_LIMITS.lineBytes) { throw new Error('UI_ANALYSIS_LINE_LIMIT'); }
    const event = parseEvent(raw.toString('utf8').replace(/\r?\n$/, ''), { line: lines, offset, bytes: raw.length, sha256: digest(raw) });
    if (event) {
      if (events.length === UI_ANALYSIS_LIMITS.events) { throw new Error('UI_ANALYSIS_EVENT_LIMIT'); }
      events.push(event);
    } else { contextLineCount++; }
    offset = end;
    if (lines % 512 === 0) { await setImmediate(); }
  }
  signal.throwIfAborted();
  if (!events.length) { throw new Error('UI_ANALYSIS_INPUT_TYPE_UNSUPPORTED'); }
  return { events, contextLineCount };
}
export function uiSummary(events: UIEvent[]): UIAnalysisSummary {
  const byStatus: UIAnalysisSummary['byStatus'] = {};
  let contextRangeEventCount = 0;
  for (const event of events) {
    byStatus[event.status] = (byStatus[event.status] ?? 0) + 1;
    if (event.currentId >= 100000 && event.currentId < 1000000) { contextRangeEventCount++; }
  }
  return { eventCount: events.length, byStatus, contextRangeEventCount };
}
interface UIAnalysisSummary { eventCount: number; byStatus: Partial<Record<WindowNotice, number>>; contextRangeEventCount: number }
